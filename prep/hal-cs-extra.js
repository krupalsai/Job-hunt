/* ============================================================================
   QUESTION BANK, VOLUME TWO — the topics prep/hal-cs.js does not reach.

   Loaded after prep/hal-cs.js and APPENDED to the same QUESTION_BANK, exactly
   as prep/ts-si.js does. Nothing here replaces anything there; the engine, the
   selection logic and the mock exam see one bank.

   WHY A SECOND FILE. Volume one covered eight subjects with no topic tags. The
   audit found 101 of the syllabus's topics with no question at all — all of
   Digital Logic, all of Algorithms as a subject, all of Compiler Design, all
   of Discrete Mathematics, and roughly a third of every subject that WAS
   covered. Writing those into volume one would have meant threading new
   questions into twelve existing arrays; a second volume keeps the diff
   readable and the origin of every question obvious.

   EVERY QUESTION CARRIES
     q          the question
     opts       four options
     correct    index of the right one
     why        WHY it is right — the reasoning, not a restatement
     trick      a hook for recalling it under exam pressure
     subtopic   the topic key from prep/syllabus.js it is practised under
     difficulty basic | moderate | hal-level | challenging
     concept    the one thing it tests, in a phrase
     source_type  always generated_practice here — see below

   DIFFICULTY, meant honestly:
     basic       a definition or a single fact
     moderate    one step of reasoning or one calculation
     hal-level   pitched at what this paper actually asks at 57 seconds each
     challenging above the paper — worth attempting, not worth panicking over

   SOURCE AND REFERENCE POLICY. Every question here is written for this app.
   Public syllabi and public question indexes (IndiaBIX among them) were used
   to decide WHICH topics to cover, at what depth, and in what proportion —
   that is a fact about the exam, not anybody's property. No question text,
   option set or explanation is reproduced from any source. `source_type` is
   "generated_practice" on all of them, and scripts/validate-prep.js refuses a
   question claiming `pyq` that cannot name its exam, year and source.

   The bias throughout is towards understanding rather than trivia: comparisons,
   the traps two similar concepts set for each other, and things that can be
   COMPUTED in under a minute. A candidate with days rather than months gets
   more from being able to work out a page-fault count than from recalling
   which year a standard was ratified.
   ========================================================================== */

